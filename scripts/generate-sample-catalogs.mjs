/**
 * Blocs lithium fer-phosphate 12,8 V (4 éléments), compatibles « classe 12 V ».
 * Énergie utile = 0,95 × U × Ah ; P(t) = E × 60 ÷ t, limitée par le courant maximal du BMS.
 */
function lfpTable(ah, maxC) {
  const e = 0.95 * 12.8 * ah;
  const pMax = 12.8 * ah * maxC;
  const pts = [5, 10, 15, 20, 30, 45, 60, 90, 120, 180, 240, 300, 480]
    .map((min) => ({ min, W: Math.round((e * 60) / min) }))
    .filter((p) => p.W <= pMax);
  return [{ eodVpc: 2.8, points: pts }];
}
