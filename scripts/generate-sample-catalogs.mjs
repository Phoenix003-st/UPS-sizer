function mono({
  id,
  ref,
  range,
  tech,
  ff,
  ru = null,
  kva,
  kw,
  dims,
  kg,
  effs,
  eco,
  battEff,
  noise,
  internal,
  bps,
  charge,
  cabs = [],
  maxCabs = 4,
  parallel = 1,
  source,
}) {
  return {
    id,
    sample: true,
    reference: `EXEMPLE ${ref}`,
    range: `EXEMPLE ${range}`,
    technology: tech,
    formFactor: ff,
    rackUnits: ru,
    power: { kVA: kva, kW: kw, pf: Math.round((kw / kva) * 100) / 100 },
    phases: { in: 1, out: 1 },
    voltages: { out: [220, 230, 240], freqHz: [50, 60] },
    efficiency: { online: effs, eco, battery: battEff },
    dimensionsMm: dims,
    weightKg: kg,
    clearancesMm: { front: 500, rear: 150, left: 0, right: 0, top: 0 },
    ip: 'IP20',
    ambientC: { min: 0, max: 40 },
    noiseDb: noise,
    battery: {
      blockVoltage: 12,
      blocksPerString: { allowed: [bps], default: bps },
      internal,
      maxChargeCurrentA: charge,
      compatibleCabinetIds: cabs,
      sharedBattery: false,
      maxExternalCabinets: maxCabs,
    },
    heatDissipationW: null,
    parallel: { capable: parallel > 1, maxUnits: parallel },
    modular: null,
    datasheetUrl: source.url,
    source,
  };
}

