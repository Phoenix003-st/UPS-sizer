/**
 * Forme de la courbe de décharge à puissance constante, normalisée à 1 pour 15 min à 1,67 V/él.
 * Points 2, 8, 15, 30 et 90 min relevés sur la fiche CSB HR1234W (688 / 324 / 206 / 119 / 50 W par
 * bloc), points intermédiaires interpolés en log-log, au-delà de 90 min extrapolés (pente ≈ −0,9).
 */
const SHAPE_167 = [
  [5, 2.03],
  [10, 1.34],
  [15, 1.0],
  [20, 0.796],
  [30, 0.577],
  [45, 0.42],
  [60, 0.335],
  [90, 0.243],
  [120, 0.188],
  [180, 0.128],
  [240, 0.099],
  [300, 0.079],
  [480, 0.05],
];
/** Rapport 1,75 V / 1,67 V (fiche HR1234W : 0,92 à 2 min, 0,963 à 8 min, 0,98 à 15 min, 0,996 à 90 min). */
const RATIO_175 = {
  5: 0.945,
  10: 0.968,
  15: 0.98,
  20: 0.981,
  30: 0.983,
  45: 0.988,
  60: 0.991,
  90: 0.996,
};

const r1 = (x) => Math.round(x * 10) / 10;
function vrlaTables(w15) {
  const t167 = SHAPE_167.map(([min, k]) => ({ min, W: r1(w15 * k) }));
  const ratio = (min) => RATIO_175[min] ?? 0.997;
  const t175 = SHAPE_167.map(([min, k]) => ({ min, W: r1(w15 * k * ratio(min)) }));
  const t170 = SHAPE_167.map(([min, k]) => ({ min, W: r1((w15 * k * (1 + ratio(min))) / 2) }));
  return [
    { eodVpc: 1.67, points: t167 },
    { eodVpc: 1.7, points: t170 },
    { eodVpc: 1.75, points: t175 },
  ];
}
